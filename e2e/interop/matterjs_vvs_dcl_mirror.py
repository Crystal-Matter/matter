#!/usr/bin/env python3
"""Local HTTPS DCL-shaped fixture for the matter.js VVS interoperability run.

The certificates are generated by the test controller and never represent
records from the production Distributed Compliance Ledger.
"""

import argparse
import base64
import json
import ssl
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path


VENDOR_ID = 0xFFF1
ROOT_PATH = f"/dcl/pki/noc-vid-root-certificates/{VENDOR_ID}"
ICA_PATH = f"/dcl/pki/noc-vid-ica-certificates/{VENDOR_ID}"


def root_response(state):
    mode = state["mode"]
    if mode == "removed":
        records = []
    elif mode in ("active", "wrong-vid", "wrong-root"):
        der = base64.b64decode(state[
            "wrong_root_der" if mode == "wrong-root" else "root_der"])
        pem = "-----BEGIN CERTIFICATE-----\n" + base64.encodebytes(der).decode() + "-----END CERTIFICATE-----\n"
        records = [{"vid": VENDOR_ID if mode != "wrong-vid" else 0xFFF2,
                    "certificateType": "OperationalPKI", "isRoot": True,
                    "pemCert": pem}]
    else:
        raise ValueError(f"unexpected DCL fixture mode: {mode}")
    return {"nocRootCertificates": {"certs": records}}


def intermediate_response(state):
    mode = state["mode"]
    if mode == "removed":
        records = []
    else:
        der = base64.b64decode(state["intermediate_der"])
        pem = "-----BEGIN CERTIFICATE-----\n" + base64.encodebytes(der).decode() + "-----END CERTIFICATE-----\n"
        records = [{"vid": VENDOR_ID, "certificateType": "OperationalPKI",
                    "isRoot": False, "pemCert": pem}]
    return {"nocIcaCertificates": {"certs": records}}


def handler_for(state_path):
    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            if self.path == ROOT_PATH:
                response = root_response(json.loads(state_path.read_text()))
            elif self.path == ICA_PATH:
                response = intermediate_response(json.loads(state_path.read_text()))
            else:
                self.send_error(404)
                return
            body = json.dumps(response).encode()
            self.send_response(200)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)

        def log_message(self, format_string, *args):
            print(format_string % args, flush=True)

    return Handler


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--state", type=Path, required=True)
    parser.add_argument("--cert", type=Path, required=True)
    parser.add_argument("--key", type=Path, required=True)
    parser.add_argument("--port", type=int, default=443)
    args = parser.parse_args()
    server = ThreadingHTTPServer(("127.0.0.1", args.port), handler_for(args.state))
    context = ssl.SSLContext(ssl.PROTOCOL_TLS_SERVER)
    context.load_cert_chain(args.cert, args.key)
    server.socket = context.wrap_socket(server.socket, server_side=True)
    print("matter.js VVS test DCL mirror listening", flush=True)
    server.serve_forever()


if __name__ == "__main__":
    main()
